// Embed runner/imagegen_runner.py into plugin/runtime.generated.ts (code only, no user data).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('..', import.meta.url).pathname;
const code = readFileSync(root + 'runner/imagegen_runner.py');
const bundle = { sha256: createHash('sha256').update(code).digest('hex'), runner: code.toString('base64') };
writeFileSync(root + 'runtime.generated.ts', '// Generated by scripts/sync_runtime.mjs\nexport const runnerBundle = ' + JSON.stringify(bundle) + ';\n');
console.log('runner sha256', bundle.sha256);
